# Builds src/content/engravings.ts and src/content/engravings/<id>.webp (files
# published beside the page): the messenger's engravings as transparent
# sepia line art (the paper made transparent, the ink kept), from public-domain
# prints at The Met (CC0). Download the originals (primaryImage from the Met's
# collection API) into one folder, named <object id>.jpg, then:
#   python3 -I scripts/content/engravings.py <folder> src/content/engravings.ts
import json, os, sys
import numpy as np
from PIL import Image, ImageFilter

ENGRAVINGS = [
    # id, met object, crop (x0, y0, x1, y1), width, paper percentile, gamma, blur, erase (x0, y0 fractions: to the corner), title
    ("rome", 363420, (0.02, 0.20, 0.98, 0.52), 1150, 85, 1.1, 0.4, None,
     "Giovanni Battista Piranesi, The Forum Romanum, or Campo Vaccino, from the Capitol, ca. 1775"),
    ("bust", 402736, (0.04, 0.03, 0.88, 0.70), 300, 80, 1.0, 0, None,
     "Nicolas Beatrizet, Bust of Livy, from the Speculum Romanae Magnificentiae, 1582"),
    ("capital", 345489, (0.02, 0.02, 0.98, 0.88), 260, 55, 1.15, 0, (0.86, 0.70),
     "Agostino Veneziano, Corinthian capital, from the Speculum Romanae Magnificentiae, 1536"),
]


def lines(path, crop, width, paper_pct, gamma, blur, erase, dest):
    im = Image.open(path).convert("L")
    w, h = im.size
    im = im.crop((int(crop[0] * w), int(crop[1] * h), int(crop[2] * w), int(crop[3] * h)))
    a = np.asarray(im.resize((width, round(im.height * width / im.width)), Image.LANCZOS)).astype(np.float32)
    paper, ink = np.percentile(a, paper_pct), np.percentile(a, 2)
    alpha = np.clip((paper - a) / max(1.0, paper - ink), 0, 1) ** gamma
    if erase:
        alpha[int(erase[1] * alpha.shape[0]):, int(erase[0] * alpha.shape[1]):] = 0
    rgba = np.zeros((*alpha.shape, 4), np.uint8)
    rgba[..., 0], rgba[..., 1], rgba[..., 2] = 58, 42, 24
    rgba[..., 3] = (alpha * 255).astype(np.uint8)
    img = Image.fromarray(rgba, "RGBA")
    if blur:
        img.putalpha(img.split()[3].filter(ImageFilter.GaussianBlur(blur)))
    img.save(dest, "WEBP", quality=40, alpha_quality=30 if width < 1000 else 25, method=6)
    return img.size


def main(src, out):
    rows = []
    files = os.path.join(os.path.dirname(out), "engravings")
    os.makedirs(files, exist_ok=True)
    for (eid, obj, crop, width, paper, gamma, blur, erase, title) in ENGRAVINGS:
        w, h = lines(os.path.join(src, f"{obj}.jpg"), crop, width, paper, gamma, blur, erase, os.path.join(files, f"{eid}.webp"))
        rows.append(f"  {eid}: " + json.dumps({"title": title, "museum": "The Met, New York", "license": "CC0", "url": f"https://www.metmuseum.org/art/collection/search/{obj}", "w": w, "h": h, "src": f"engravings/{eid}.webp"}, ensure_ascii=False) + ",")
    text = "\n".join([
        "// Engravings for the messenger's scene (Piranesi's Forum behind the top bar,",
        "// a Corinthian capital at the page sides, Livy's bust under the chat list), as",
        "// transparent sepia line art from public-domain prints at The Met (CC0), as",
        "// WebP files in src/content/engravings published beside the page.",
        "// Generated by scripts/content/engravings.py: do not edit by hand.",
        "",
        "export interface Engraving {",
        "  title: string;",
        "  museum: string;",
        "  license: string;",
        "  url: string;",
        "  w: number;",
        "  h: number;",
        "  /** The file, beside the page. */",
        "  src: string;",
        "}",
        "",
        "export const ENGRAVINGS: Record<\"rome\" | \"bust\" | \"capital\", Engraving> = {",
        *rows,
        "};",
        "",
    ])
    with open(out, "w") as fh:
        fh.write(text)


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
